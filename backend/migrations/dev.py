"""
Migration tooling for development (the app doesn't use this at runtime).

    python -m backend.migrations.dev revision "add a rating to tracks"
        After changing backend/models.py: writes versions/NNNN_<message>.py
        with the operations that bring the schema from the latest migration
        to the models. Read it before committing:
        - A new NOT NULL column needs a value for the rows already there:
          add server_default=... to its sa.Column in the script (the
          models' default= only applies to rows the app inserts).
        - A renamed column or table comes out as a drop plus an add, which
          loses its data: replace them with batch_op.alter_column(...,
          new_column_name=...) or op.rename_table.
        - Primary key and AUTOINCREMENT changes aren't generated at all:
          the warning says what to add by hand.
        - Data changes (filling a new column from existing ones) have to
          be written by hand, with op.execute or op.get_bind().
        It prints a warning for each of the first three it can spot.

    python -m backend.migrations.dev check
        Fails if the models have changes no migration covers.

Both build a throwaway database from versions/ to compare against, so they
need neither /config nor a running app. See README > Development.
"""
from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

from alembic import command
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected, CommandError

from . import runner


def _next_revision_id(cfg) -> str:
    """Revisions are numbered 0001, 0002... so versions/ lists in order."""
    numbers = [int(s.revision) for s in ScriptDirectory.from_config(cfg).walk_revisions() if s.revision.isdigit()]
    return f"{max(numbers, default=0) + 1:04d}"


def _run_on_scratch_db(action) -> None:
    """Call action(cfg) with a database brought up to the latest migration."""
    with tempfile.TemporaryDirectory() as tmp:
        engine = runner.migration_engine(Path(tmp) / "scratch.sqlite")
        try:
            with engine.connect() as conn, conn.begin():
                cfg = runner.alembic_config()
                cfg.attributes["connection"] = conn
                command.upgrade(cfg, "head")
                action(cfg)
        finally:
            engine.dispose()


def cmd_revision(message: str) -> int:
    created = []
    warnings = []

    def generate(cfg) -> None:
        cfg.attributes["new_revision"] = True  # see env._review_new_revision
        # The scratch database is at the latest migration: what differs from
        # the models there, autogenerate won't write into the new one
        warnings.extend(
            f"not generated, add it by hand: {diff}"
            for diff in runner.diffs_alembic_misses(cfg.attributes["connection"])
        )
        result = command.revision(cfg, message=message, autogenerate=True, rev_id=_next_revision_id(cfg))
        # A script, or a list of them (empty when there was nothing to generate)
        for script in result if isinstance(result, list) else [result]:
            if script is not None:
                created.append(script.path)
        warnings.extend(cfg.attributes.get("warnings", []))

    _run_on_scratch_db(generate)
    if not created:
        print("The models match the latest migration: nothing to generate.")
        return 0
    print(f"Wrote {created[0]}\nRead it before committing (see this module's docstring).")
    for warning in warnings:
        print(f"warning: {warning}", file=sys.stderr)
    return 0


def cmd_check() -> int:
    missed = []

    def check(cfg) -> None:
        ScriptDirectory.from_config(cfg).get_current_head()  # raises if the history forked
        command.check(cfg)
        missed.extend(runner.diffs_alembic_misses(cfg.attributes["connection"]))

    try:
        _run_on_scratch_db(check)
    except AutogenerateDiffsDetected as e:
        print(f"The models have changes no migration covers:\n{e}", file=sys.stderr)
        return 1
    except CommandError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    if missed:
        print("The models have changes no migration covers:\n  " + "\n  ".join(missed), file=sys.stderr)
        return 1
    print("The models match the migrations.")
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="python -m backend.migrations.dev", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("revision", help="generate a migration from the changes to backend/models.py")
    p.add_argument("message", help='what it changes, e.g. "add a rating to tracks"')
    sub.add_parser("check", help="fail if the models have changes no migration covers")
    args = parser.parse_args(argv)

    if args.command == "revision":
        return cmd_revision(args.message)
    return cmd_check()


if __name__ == "__main__":
    sys.exit(main())
